// Refuse a public source link that points at a MOVING ref in the core or apps repository.
//
// WHY THIS GATE EXISTS. This site publishes released state, and `/compare` is already held
// to that rule mechanically: validate-compare-render.mjs fails a row whose `source_url`
// does not point into the pinned release tag, because "a row sourced to a branch can be
// true in development and false in the release a reader can actually install" (README,
// "Claims about our own capabilities").
//
// That rule was enforced for /compare rows and nowhere else, so the same defect had
// accumulated in hand-written page copy, where it is harder to see and carries more weight:
//
//   - /security sent every reader of the threat model, the limitations page and the
//     vulnerability policy to core's DEFAULT BRANCH. A security document read there can
//     describe a control the released build does not have — the single worst place on the
//     site for a branch link.
//   - /apps pointed the app-creation guide at the apps default branch, which can document a
//     manifest field the released core rejects.
//   - The app directory built 39 card links into `PersonalClawApps/tree/main/<slug>`, on a
//     page whose every count is derived from the pinned apps commit.
//
// None of those would ever have been caught by a build, a link check or a screenshot: the
// URLs resolve, they are just answering a different question than the page is asking.
//
// WHAT COUNTS AS A MOVING REF: `main`, `master`, `HEAD`, or `latest`. A commit SHA or a
// `v*` tag is immutable and passes. Links are expected to be built from
// `releaseFacts.core.source` / `releaseFacts.apps.source`, which carry the pinned commit.
//
// SCOPE: hand-authored content only. `src/content/docs/` is deliberately excluded — it is
// generated by scripts/sync-docs.mjs from the pinned revision, and that script already
// rewrites every out-of-corpus link to the pinned commit. Auditing generated output here
// would be checking sync-docs' work in the wrong place.

import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = dirname(dirname(fileURLToPath(import.meta.url)));

/** Directories of hand-authored content. `src/content/docs` is generated — see header. */
const SCANNED = [
  "src/pages",
  "src/components",
  "src/data",
  "src/layouts",
  "src/content/blog",
  "src/prose",
];

const SCANNED_EXTENSIONS = [".astro", ".ts", ".tsx", ".mjs", ".js", ".json", ".md"];

/** The repositories whose released state this site publishes. */
const PINNED_REPOSITORIES = ["PersonalClaw/PersonalClaw", "PersonalClaw/PersonalClawApps"];

const MOVING_REFS = ["main", "master", "HEAD", "latest"];

/**
 * Two shapes, because half the offenders were template literals whose repository segment
 * was interpolated (`${source.repository}/tree/main/...`) and a URL-only regex reads a
 * clean zero on those — the exact false negative that let them accumulate.
 */
const FULL_URL = new RegExp(
  `github\\.com/(${PINNED_REPOSITORIES.join("|")})/(?:blob|tree|raw)/(${MOVING_REFS.join("|")})(?=[/"'\`\\s)]|$)`,
  "g",
);
const INTERPOLATED_REF = new RegExp(
  `\\$\\{[^}]*\\}/(?:blob|tree|raw)/(${MOVING_REFS.join("|")})(?=[/"'\`\\s)]|$)`,
  "g",
);

/**
 * Links that are branch-pinned ON PURPOSE, each with the reason it cannot be pinned.
 * An entry earns its place by naming a condition under which the pinned path DOES NOT
 * EXIST — not by being inconvenient to fix.
 */
const ALLOWED = [
  {
    file: "src/pages/registry.astro",
    reason:
      "The `absent-at-pin` branch only runs when the community registry does not exist " +
      "at the pinned commit, so there is no pinned path to link to. The ternary's other " +
      "arm is commit-pinned, and README 'Content And Release Truth' documents this " +
      "fallback as the honest alternative to reading core's default branch as released " +
      "state.",
  },
];

function walk(directory) {
  const absolute = join(repositoryRoot, directory);
  let entries;
  try {
    entries = readdirSync(absolute, { withFileTypes: true });
  } catch {
    return [];
  }
  return entries.flatMap((entry) => {
    const next = join(directory, entry.name);
    if (entry.isDirectory()) return walk(next);
    if (!SCANNED_EXTENSIONS.some((extension) => entry.name.endsWith(extension))) return [];
    return [next];
  });
}

const allowedFiles = new Set(ALLOWED.map((entry) => entry.file));
const problems = [];
const allowedHits = [];
let scannedFiles = 0;
let linkCount = 0;

for (const directory of SCANNED) {
  for (const file of walk(directory)) {
    scannedFiles += 1;
    const contents = readFileSync(join(repositoryRoot, file), "utf8");
    const lines = contents.split("\n");

    lines.forEach((line, index) => {
      for (const pattern of [FULL_URL, INTERPOLATED_REF]) {
        pattern.lastIndex = 0;
        let match;
        while ((match = pattern.exec(line)) !== null) {
          linkCount += 1;
          const ref = match[match.length - 1];
          const location = `${file}:${index + 1}`;
          if (allowedFiles.has(file)) {
            allowedHits.push(`${location} (ref \`${ref}\`)`);
            continue;
          }
          problems.push(
            `${location}: links into a pinned repository at the moving ref \`${ref}\`. ` +
              `This page describes the RELEASE, so build the URL from ` +
              `releaseFacts.core.source.commit / releaseFacts.apps.source.commit (or link ` +
              `the in-site /docs route, which is generated from the pin). If the link ` +
              `genuinely cannot be pinned, add it to ALLOWED in this script with the ` +
              `reason.`,
          );
        }
      }
    });
  }
}

// An allowlist entry that stops matching is itself a problem: it means the exception was
// fixed or moved, and a stale waiver is how the next branch link gets in unnoticed.
for (const entry of ALLOWED) {
  if (!allowedHits.some((hit) => hit.startsWith(`${entry.file}:`))) {
    problems.push(
      `${entry.file}: listed in ALLOWED but has no branch-pinned link any more. Remove ` +
        `the entry — a waiver nobody needs is a waiver that silently covers the next one.`,
    );
  }
}

const relativeRoot = relative(process.cwd(), repositoryRoot) || ".";
console.log(
  `Source pins: scanned ${scannedFiles} hand-authored file(s) under ${relativeRoot}, ` +
    `found ${linkCount} link(s) at a moving ref (${allowedHits.length} allowed).`,
);
for (const hit of allowedHits) console.log(`  allowed: ${hit}`);

if (problems.length > 0) {
  console.error(`\n${problems.length} branch-pinned source link problem(s):`);
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exitCode = 1;
} else {
  console.log("No unpinned source links.");
}
