export function canonicalUrl(path) {
  return new URL(path, siteOrigin).toString();
}

export function routeOutputPath(path) {
  return path === "/" ? "index.html" : `${path.slice(1)}/index.html`;
}

/**
 * The route path a built HTML file is published at — the inverse of `routeOutputPath`.
 * Used by the universal head sweep, which walks the build output rather than a list.
 */
export function outputPathRoute(outputPath) {
  if (outputPath === "index.html") return "/";
  if (outputPath === "404.html") return "/404";
  return `/${outputPath.replace(/\/index\.html$/, "")}`;
}
